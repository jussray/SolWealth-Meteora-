import assert from "node:assert/strict";
import test from "node:test";

import {
  AccountModel,
  CUSTOMER_GATES,
  POOLED_GATES,
  evaluateAccountScope,
  signReceipt,
  verifyGateReceipt,
} from "../src/accounts/account-scope.mjs";

const KEY = "k".repeat(32);
const ISSUER = "trusted-runtime";
const NOW = new Date("2030-01-01T00:00:00Z");

function receipt(gate, subject, { key = KEY, expires = "2031-01-01T00:00:00+00:00", issuer = ISSUER } = {}) {
  const fields = { gate, subject, issued_by: issuer, expires_at: expires };
  return { ...fields, signature: signReceipt(fields, key) };
}
const all = (gates, subject, opts) => gates.map((g) => receipt(g, subject, opts));
const run = (model, subject, receipts, extra = {}) =>
  evaluateAccountScope({ model, subject, receipts, key: KEY, now: NOW, trustedIssuers: [ISSUER], capitalCeiling: 1000, ...extra });

test("signature matches the Python SleepWealth evaluator (cross-language vector)", () => {
  // Generated by execution/account_models.sign_receipt with key b"k"*32.
  const fields = { gate: "customer_consent", subject: "cust-1", issued_by: "trusted-runtime", expires_at: "2030-01-02T00:00:00+00:00" };
  assert.equal(signReceipt(fields, KEY), "fe9f2b62f40efc662e92a73375c539f1e05ad43ca51f16079e329a3c2fe7b868");
});

test("no receipts blocks and names every missing gate", () => {
  const r = run(AccountModel.CUSTOMER_CONNECTED, "cust-1", []);
  assert.equal(r.status, "BLOCKED");
  assert.deepEqual(r.missing_or_invalid_gates, [...CUSTOMER_GATES].sort());
  assert.equal(r.live_execution_authorized, false);
});

test("customer scope is eligible only with all customer receipts, and never authorizes live", () => {
  const r = run(AccountModel.CUSTOMER_CONNECTED, "cust-1", all(CUSTOMER_GATES, "cust-1"));
  assert.equal(r.status, "ELIGIBLE_FOR_LIVE_GATE_REVIEW");
  assert.equal(r.live_execution_authorized, false);
  assert.equal(r.authorizes_real_money, false);
});

test("pooled gates cannot be satisfied by customer receipts", () => {
  const r = run(AccountModel.POOLED_MANAGED, "pool-1", all(CUSTOMER_GATES, "pool-1"));
  assert.equal(r.status, "BLOCKED");
  assert.deepEqual(r.missing_or_invalid_gates, [...POOLED_GATES].sort());
});

test("receipts for another subject, expired receipts, untrusted issuers and wrong keys are rejected", () => {
  assert.ok(run(AccountModel.CUSTOMER_CONNECTED, "cust-2", all(CUSTOMER_GATES, "cust-1")).reasons.every((x) => x.endsWith("subject_mismatch")));
  assert.ok(run(AccountModel.CUSTOMER_CONNECTED, "cust-1", all(CUSTOMER_GATES, "cust-1", { expires: "2029-01-01T00:00:00Z" })).reasons.every((x) => x.endsWith("receipt_expired")));
  assert.ok(run(AccountModel.CUSTOMER_CONNECTED, "cust-1", all(CUSTOMER_GATES, "cust-1", { issuer: "random" })).reasons.every((x) => x.endsWith("untrusted_issuer")));
  assert.ok(run(AccountModel.CUSTOMER_CONNECTED, "cust-1", all(CUSTOMER_GATES, "cust-1", { key: "x".repeat(32) })).reasons.every((x) => x.endsWith("signature_invalid")));
});

test("tampered receipt fails signature", () => {
  const receipts = all(CUSTOMER_GATES, "cust-1");
  receipts[1] = { ...receipts[1], expires_at: "2099-01-01T00:00:00Z" };
  assert.ok(run(AccountModel.CUSTOMER_CONNECTED, "cust-1", receipts).reasons.includes("broker_oauth_grant:signature_invalid"));
});

test("short or missing trusted key fails closed", () => {
  const r = verifyGateReceipt(receipt("customer_consent", "cust-1"), { gate: "customer_consent", subject: "cust-1", key: "short", now: NOW, trustedIssuers: [ISSUER] });
  assert.equal(r, "trusted_key_missing_or_short");
  assert.throws(() => signReceipt({ a: 1 }, "short"), /at least 32 bytes/);
});

test("invalid capital ceilings and blank subjects are rejected", () => {
  for (const c of [0, -1, NaN, Infinity, "100"]) {
    assert.equal(run(AccountModel.CUSTOMER_CONNECTED, "cust-1", all(CUSTOMER_GATES, "cust-1"), { capitalCeiling: c }).status, "REJECTED");
  }
  assert.equal(run(AccountModel.POOLED_MANAGED, "  ", all(POOLED_GATES, "  ")).status, "REJECTED");
});

test("pooled scope eligible only with all pooled receipts; one missing gate blocks", () => {
  assert.equal(run(AccountModel.POOLED_MANAGED, "pool-1", all(POOLED_GATES, "pool-1")).status, "ELIGIBLE_FOR_LIVE_GATE_REVIEW");
  const r = run(AccountModel.POOLED_MANAGED, "pool-1", all(POOLED_GATES, "pool-1").slice(0, -1));
  assert.deepEqual(r.missing_or_invalid_gates, [POOLED_GATES[POOLED_GATES.length - 1]]);
});
